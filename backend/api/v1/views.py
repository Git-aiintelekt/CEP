class BaseTenantViewSet(viewsets.ModelViewSet):
    """Every queryset is filtered by the request tenant (RLS is the safety net, not the only filter);
    tenant and created_by are stamped on create; the acting user is pushed into the RLS session for the audit trail."""
    permission_classes = [IsAuthenticated, SameTenant]
    permission_code = None                                # e.g. "campaign.edit"
    soft_delete = True

    def get_permissions(self):
        perms = super().get_permissions()
        if self.permission_code:
            perms.append(HasPermissionCode.for_(self.permission_code)())
        return perms

    def initial(self, request, *args, **kwargs):
        super().initial(request, *args, **kwargs)
        user = request.user
        if getattr(user, "is_authenticated", False) and not hasattr(user, "has_scope"):
            set_current_user(user.id)

    def get_queryset(self):
        qs = super().get_queryset().filter(tenant_id=context.require().tenant_id)
        if self.soft_delete and hasattr(qs.model, "deleted_at"):
            qs = qs.filter(deleted_at__isnull=True)
        return qs

    def perform_create(self, serializer):
        kwargs = {"tenant_id": context.require().tenant_id}
        user = self.request.user
        if hasattr(serializer.Meta.model, "created_by") and not hasattr(user, "has_scope"):
            kwargs["created_by_id"] = user.id
        serializer.save(**kwargs)

    def perform_destroy(self, instance):
        if self.soft_delete and hasattr(instance, "deleted_at"):
            from django.utils import timezone
            instance.deleted_at = timezone.now()
            instance.save(update_fields=["deleted_at"])
        else:
            instance.delete()


class CampaignViewSet(BaseTenantViewSet):
    queryset = (Campaign.objects.select_related("template", "sender_profile")
                .prefetch_related("campaign_runs", "contact_list_campaigns__contact_list"))
    EDITABLE = (Campaign.Status.DRAFT, Campaign.Status.TEST_PUBLISHED)

    def perform_create(self, serializer):
        user = self.request.user
        extra = {} if hasattr(user, "has_scope") else {"owner_user_id": user.id, "created_by_id": user.id}
        serializer.save(tenant_id=context.require().tenant_id, **extra)

    def perform_update(self, serializer):
        campaign = serializer.instance
        if campaign.is_journey_generated:
            raise Conflict("This campaign is generated by a journey. Change the journey instead.")
        if campaign.status not in self.EDITABLE:
            raise Conflict(f"A {campaign.get_status_display().lower()} campaign can no longer be edited.")
        expected = self.request.data.get("row_version")
        if expected is not None and str(expected) != str(campaign.row_version):
            raise Conflict("Someone else changed this campaign after you opened it. Reload to see their changes.")
        serializer.save()

    def perform_destroy(self, instance):
        if instance.status != Campaign.Status.DRAFT or instance.campaign_runs.exists():
            raise Conflict("Only a draft campaign that has never run can be deleted.")
        super().perform_destroy(instance)
    serializer_class = s.CampaignSerializer
    permission_code = "campaign.edit"
    filterset_fields = ["status", "campaign_type", "channel", "solicitation_type"]
    search_fields = ["name", "code"]
    ordering_fields = ["created_at", "scheduled_at", "name"]

    @action(detail=True, methods=["post"], permission_classes=[IsAuthenticated, HasPermissionCode.for_("campaign.publish")])
    def publish(self, request, pk=None, version=None):
        """Moves a DRAFT / TEST_PUBLISHED campaign to PRODUCTION_PUBLISHED and creates run #1 (the worker builds the list)."""
        campaign = self.get_object()
        if campaign.status not in self.EDITABLE:
            raise Conflict("Campaign cannot be published from its current status.")
        missing = {}
        if campaign.template_id is None:
            missing["template"] = "Choose a template before publishing."
        if campaign.sender_profile_id is None:
            missing["sender_profile"] = "Choose a sender before publishing."
        elif campaign.sender_profile.deleted_at is not None:
            missing["sender_profile"] = "This sender was removed. Choose another one."
        elif campaign.sender_profile.verification_status != "VERIFIED":
            missing["sender_profile"] = "This sender is not verified yet."
        if campaign.campaign_type != Campaign.CampaignType.E_RECEIPT and not campaign.contact_list_campaigns.exists():
            missing["contact_lists"] = "Attach at least one contact list before publishing."
        if campaign.template_id is not None and "template" not in missing:
            content = (RenderedTemplateContent.objects.filter(template_id=campaign.template_id).order_by("-version_number").first())
            body = ((content.html_content or "") + (content.sms_body or "")) if content else ""
            if not body.strip():
                missing["template"] = "This template has no saved content yet."
            elif (campaign.solicitation_type == Campaign.SolicitationType.MARKETING and campaign.template.channel == "EMAIL"
                  and design.UNSUBSCRIBE_TAG not in design.extract_tags(body)):
                missing["template"] = "Marketing email must contain the {{unsubscribe_url}} link."
            elif (campaign.solicitation_type == Campaign.SolicitationType.MARKETING and campaign.template.channel in design.MESSAGE_CHANNELS
                  and not design.OPT_OUT_RE.search(body)):
                missing["template"] = "Marketing text messages must say how to opt out, for example: Reply STOP to unsubscribe."
            elif campaign.template.channel == "MMS" and design.message_blockers(campaign.template).get("media_asset"):
                missing["template"] = "This MMS template has no picture."
        if missing:
            raise ValidationError(missing)
        billing.assert_can_send(campaign.tenant_id)          # 409 when a hard-capped plan has used its messages this month
        campaign.status = Campaign.Status.PRODUCTION_PUBLISHED
        campaign.save(update_fields=["status"])
        run = CampaignRun.objects.create(campaign=campaign, tenant_id=campaign.tenant_id, run_number=campaign.campaign_runs.count() + 1,
                                         run_type=CampaignRun.RunType.ONE_TIME, scheduled_at=campaign.scheduled_at)
        return Response(s.CampaignRunSerializer(run).data, status=201)


