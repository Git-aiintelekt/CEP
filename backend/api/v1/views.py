class TemplateViewSet(BaseTenantViewSet):
    # rendered content is the authority for versions: messages and imported templates may have no editor state
    queryset = TemplateMaster.objects.annotate(latest_version=Max("rendered_template_contents__version_number"))
    serializer_class = s.TemplateSerializer
    permission_code = "template.edit"
    filterset_fields = ["channel", "status"]
    search_fields = ["name"]

    def perform_update(self, serializer):
        if serializer.instance.status == TemplateMaster.Status.ARCHIVED:
            raise Conflict("An archived template cannot be changed.")
        serializer.save()

    def perform_destroy(self, instance):
        if instance.campaigns.filter(deleted_at__isnull=True).exists():
            raise Conflict("This template is used by a campaign. Archive it instead.")
        super().perform_destroy(instance)

    @extend_schema(methods=["GET"], responses=s.DesignSerializer,
                   parameters=[OpenApiParameter("version", int, description="a stored version; default latest")])
    @extend_schema(methods=["POST"], request=s.DesignSaveSerializer, responses={201: s.DesignSerializer})
    @action(detail=True, methods=["get", "post"])
    def design(self, request, pk=None, version=None):
        """GET the design the editor loads (latest, or ?version=n). POST saves a NEW version; the HTML is rendered
        on the server from the MJML, and 409 is returned when base_version is no longer the latest."""
        template = self.get_object()
        if request.method == "GET":
            wanted = request.query_params.get("version")
            if wanted is not None and not wanted.isdigit():
                raise ValidationError({"version": "Expected a version number."})
            return Response(design.design_payload(template, int(wanted) if wanted else None))
        body = s.DesignSaveSerializer(data=request.data)
        body.is_valid(raise_exception=True)
        user = request.user
        saved = design.save_design(template, None if hasattr(user, "has_scope") else user.id, **body.validated_data)
        return Response(saved, status=201)

    @extend_schema(responses=s.DesignVersionSerializer(many=True))
    @action(detail=True, methods=["get"], url_path="design/versions", pagination_class=None)
    def design_versions(self, request, pk=None, version=None):
        template = self.get_object()
        authors = {state.version_number: state for state in TemplateDesignState.objects.filter(template=template)
                   .select_related("created_by").defer("editor_state")}
        rows = []
        for content in (RenderedTemplateContent.objects.filter(template=template).only("version_number", "rendered_at")
                        .order_by("-version_number")[:100]):
            state = authors.get(content.version_number)
            rows.append({"version_number": content.version_number, "saved_at": state.created_at if state else content.rendered_at,
                         "saved_by": state.created_by.display_name if state and state.created_by else None})
        return Response(s.DesignVersionSerializer(rows, many=True).data)

    @extend_schema(methods=["GET"], responses=s.MessageSerializer,
                   parameters=[OpenApiParameter("version", int, description="a stored version; default latest")])
    @extend_schema(methods=["POST"], request=s.MessageSaveSerializer, responses={201: s.MessageSerializer})
    @action(detail=True, methods=["get", "post"])
    def message(self, request, pk=None, version=None):
        """SMS / MMS counterpart of `design`: GET the message the editor loads, POST saves a new version. Findings carry
        the encoding and segment count estimated with the tags' sample values."""
        template = self.get_object()
        if template.channel not in design.MESSAGE_CHANNELS:
            raise Conflict("The message editor is for SMS and MMS templates.")
        if request.method == "GET":
            wanted = request.query_params.get("version")
            if wanted is not None and not wanted.isdigit():
                raise ValidationError({"version": "Expected a version number."})
            return Response(design.message_payload(template, int(wanted) if wanted else None))
        body = s.MessageSaveSerializer(data=request.data)
        body.is_valid(raise_exception=True)
        user = request.user
        saved = design.save_message(template, None if hasattr(user, "has_scope") else user.id, **body.validated_data)
        return Response(saved, status=201)

    @extend_schema(request=None, responses=s.TemplateSerializer)
    @action(detail=True, methods=["post"])
    def activate(self, request, pk=None, version=None):
        """DRAFT -> ACTIVE once the template is sendable: saved design, subject line, only known tags."""
        template = self.get_object()
        if template.status == TemplateMaster.Status.ARCHIVED:
            raise Conflict("An archived template cannot be activated.")
        blockers = design.activation_blockers(template)
        if blockers:
            raise ValidationError(blockers)
        template.status = TemplateMaster.Status.ACTIVE
        template.save(update_fields=["status"])
        return Response(self.get_serializer(self.get_queryset().get(pk=template.pk)).data)

    @extend_schema(request=None, responses=s.TemplateSerializer)
    @action(detail=True, methods=["post"])
    def archive(self, request, pk=None, version=None):
        template = self.get_object()
        if template.campaigns.filter(deleted_at__isnull=True, status__in=["PRODUCTION_PUBLISHED", "ACTIVE", "TEST_PUBLISHED"]).exists():
            raise Conflict("A live campaign uses this template.")
        template.status = TemplateMaster.Status.ARCHIVED
        template.save(update_fields=["status"])
        return Response(self.get_serializer(self.get_queryset().get(pk=template.pk)).data)


