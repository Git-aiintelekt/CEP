class MediaAssetViewSet(mixins.ListModelMixin, mixins.CreateModelMixin, viewsets.GenericViewSet):
    """Images for the template designer. Content-addressed: the same file uploaded twice is stored once per tenant."""
    queryset = MediaAsset.objects.filter(deleted_at__isnull=True, asset_kind="IMAGE", visibility="PUBLIC").order_by("-created_at")
    serializer_class = s.MediaAssetSerializer
    permission_classes = [IsAuthenticated, SameTenant, HasPermissionCode.for_("template.edit")]
    parser_classes = [MultiPartParser]
    search_fields = ["file_name"]
    FORMATS = {"PNG": ("image/png", ".png"), "JPEG": ("image/jpeg", ".jpg"), "GIF": ("image/gif", ".gif"), "WEBP": ("image/webp", ".webp")}

    def get_queryset(self):
        return super().get_queryset().filter(tenant_id=context.require().tenant_id)

    @extend_schema(request={"multipart/form-data": {"type": "object", "properties": {"file": {"type": "string", "format": "binary"}},
                                                    "required": ["file"]}}, responses={201: s.MediaAssetSerializer})
    def create(self, request, *args, **kwargs):
        upload = request.FILES.get("file")
        if upload is None:
            raise ValidationError({"file": "Attach an image in the 'file' field."})
        limit_mb = max(1, min(int(params.get("messaging.max_upload_mb", 5)), 25))          # global parameter, kept within sane bounds
        if upload.size > limit_mb * 1024 * 1024:
            raise ValidationError({"file": f"Images can be at most {limit_mb} MB."})
        data = upload.read()
        try:                                                          # trust the bytes, not the file name or Content-Type
            Image.open(io.BytesIO(data)).verify()
            image = Image.open(io.BytesIO(data))
        except (UnidentifiedImageError, OSError, SyntaxError, ValueError):
            raise ValidationError({"file": "This file is not a valid image."}) from None
        if image.format not in self.FORMATS:
            raise ValidationError({"file": "Use PNG, JPEG, GIF or WebP (SVG is not supported by email clients)."})
        mime, extension = self.FORMATS[image.format]
        tenant_id = context.require().tenant_id
        checksum = hashlib.sha256(data).hexdigest()

        asset = MediaAsset.objects.filter(tenant_id=tenant_id, checksum_sha256=checksum).first()
        if asset is not None:
            if asset.deleted_at is not None:
                asset.deleted_at = None
                asset.save(update_fields=["deleted_at"])
            return Response(self.get_serializer(asset).data, status=200)

        key = f"img/{checksum[:2]}/{checksum}{extension}"              # immutable, cacheable for a year
        if not settings.MEDIA_BUCKET:
            key = f"t/{tenant_id}/{key}"                                # the S3 storage already prefixes the tenant
        if not default_storage.exists(key):
            default_storage.save(key, ContentFile(data))
        url = default_storage.url(key)
        user = request.user
        asset = MediaAsset.objects.create(
            tenant_id=tenant_id, file_name=upload.name[:255], mime_type=mime, byte_size=len(data), storage_key=key,
            public_url=url if url.startswith("http") else request.build_absolute_uri(url), checksum_sha256=checksum,
            width_px=image.width, height_px=image.height, asset_kind="IMAGE", visibility="PUBLIC", scan_status="SKIPPED",
            uploaded_via="API", created_by_id=None if hasattr(user, "has_scope") else user.id)
        return Response(self.get_serializer(asset).data, status=201)


