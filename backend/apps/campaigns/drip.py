"""Drip steps (patch 0040): each message of a drip campaign is a CampaignDripStep with its own template copy.

    timetable     everyone starts together on the start date (campaign.scheduled_at); a step's day counts from it (0-365),
                  sent at its own send_time or the series time (drip_config.time).
    templates     every step owns its copy ("{campaign} · 2 of 4", renumbered while the drip is editable), so editing one
                  message never changes another. Backfilled drips are the exception: their steps share the campaign's
                  template (template_owned = False), which the drip never renames or removes.
    mirror        until the send engine reads the steps (B2), publish and the engine read drip_config.steps and
                  campaign.template_id: sync() rewrites both from the rows after every change.
    locks         a template used by a step can't be changed while its drip is live, nor deleted or archived while it runs.
"""
from datetime import datetime, time, timedelta

from django.db.models import Q
from django.utils import timezone
from rest_framework.exceptions import ValidationError

from api.exceptions import Conflict

from . import approval, service
from .models import Campaign, CampaignDripStep

S = Campaign.Status
MAX_STEPS = 30
DEFAULT_GAP_DAYS = 3
RUNNING = (S.TEST_PUBLISHED, S.PRODUCTION_PUBLISHED, S.ACTIVE, S.PAUSED)      # its templates can't be deleted or archived ("Scheduled" is production published)
LIVE = (S.PRODUCTION_PUBLISHED, S.ACTIVE, S.PAUSED)                           # its templates can't be changed at all
TEXT_CHANNELS = ("SMS", "MMS")
SAME_DAY = "Another message is already on this day."
KIND = {"EMAIL": "an email", "SMS": "an SMS", "MMS": "an MMS"}
SENDS = {"EMAIL": "email", "SMS": "texts", "MMS": "picture messages"}


def _user_id(user):
    return None if user is None or hasattr(user, "has_scope") else user.pk


def steps_of(campaign) -> list[CampaignDripStep]:
    return list(CampaignDripStep.objects.filter(campaign=campaign).select_related("template").order_by("day"))


def require_editable(campaign) -> None:
    if campaign.is_journey_generated:
        raise Conflict("This campaign is generated by a journey. Change the journey instead.")
    if campaign.status not in service.EDITABLE:
        raise Conflict(f"A {campaign.get_status_display().lower()} campaign can no longer be edited.")


# ---------------------------------------------------------------- names and the mirror
def copy_name(campaign, position: int, count: int) -> str:
    suffix = f" · {position} of {count}"
    return campaign.name[:200 - len(suffix)] + suffix


def _free_name(wanted: str, exclude_id=None) -> str:
    """`wanted`, or `wanted 2`, `wanted 3`... while another live template has it (ux_template_master_name_live)."""
    from apps.templates.models import TemplateMaster
    stem, candidate, number = wanted, wanted, 2
    taken = TemplateMaster.objects.filter(deleted_at__isnull=True).exclude(pk=exclude_id)
    while taken.filter(name__iexact=candidate).exists():
        tail = f" {number}"
        candidate, number = stem[:200 - len(tail)] + tail, number + 1
    return candidate


def _renumber(campaign, steps) -> None:
    from apps.templates.models import TemplateMaster
    wanted = {step.template_id: copy_name(campaign, position, len(steps))
              for position, step in enumerate(steps, start=1) if step.template_owned and step.template_id and step.template.deleted_at is None}
    changing = [template_id for template_id, name in wanted.items() if TemplateMaster.objects.filter(pk=template_id).values_list("name", flat=True).first() != name]
    for template_id in changing:                          # out of the way first: reordering swaps names between the copies
        TemplateMaster.objects.filter(pk=template_id).update(name=f"~{template_id}")
    for template_id in changing:
        TemplateMaster.objects.filter(pk=template_id).update(name=_free_name(wanted[template_id], exclude_id=template_id))


def sync(campaign) -> list[CampaignDripStep]:
    """After every step change: renumber the copies' names (while editable), then rewrite drip_config.steps and
    campaign.template_id from the rows, which is what publish, preview, the checklist and the send engine read until B2."""
    steps = steps_of(campaign)
    if campaign.status in service.EDITABLE:
        _renumber(campaign, steps)
    config = dict(campaign.drip_config or {})
    config["steps"] = [{"day": step.day, **({"label": step.name} if step.name else {})} for step in steps]
    template_id = steps[0].template_id if steps else campaign.template_id
    changed = [name for name, value in (("drip_config", config), ("template_id", template_id)) if getattr(campaign, name) != value]
    if changed:
        campaign.drip_config, campaign.template_id = config, template_id
        campaign.save(update_fields=changed)
    return steps_of(campaign) if campaign.status in service.EDITABLE else steps


def _changed(campaign, user, message: str) -> None:
    service.record(campaign, "MODIFIED", message, user=user)
    approval.withdraw(campaign, user, message[0].lower() + message[1:])


# ---------------------------------------------------------------- template copies
def _check_template(campaign, template) -> None:
    if template is None or str(template.tenant_id) != str(campaign.tenant_id) or template.deleted_at is not None:
        raise ValidationError({"template": ["Choose one of this workspace's templates."]})
    if template.status == "ARCHIVED":
        raise ValidationError({"template": ["This template is archived."]})
    if template.channel != campaign.channel:
        raise ValidationError({"template": [f"Choose {KIND.get(campaign.channel, 'a matching')} template. This drip sends {SENDS.get(campaign.channel, 'one channel')}."]})


def _copy_of(campaign, template, user, name: str):
    from apps.templates import design
    _check_template(campaign, template)
    return design.clone_template(template, _user_id(user), name=_free_name(name))


def _blank(campaign, user, name: str):
    from apps.templates.models import TemplateMaster
    if campaign.channel not in ("EMAIL", *TEXT_CHANNELS):
        raise ValidationError({"start_from": ["Choose the drip's channel first."]})
    return TemplateMaster.objects.create(tenant_id=campaign.tenant_id, name=_free_name(name), channel=campaign.channel, status=TemplateMaster.Status.DRAFT,
                                         created_by_id=_user_id(user))


def _from_starter(campaign, key: str, user, name: str):
    from apps.templates import starters
    starter = starters.BY_KEY.get(key or "")
    if starter is None:
        raise ValidationError({"starter": ["Unknown starter."]})
    if starter["channel"] != campaign.channel:
        raise ValidationError({"starter": [f"The {starter['name']} starter is for {starter['channel']} templates."]})
    template = _blank(campaign, user, name)
    starters.apply(template, _user_id(user), key)
    return template


def consume_source(template, user) -> bool:
    """consume_source: the template a message was just copied from goes, when it was only ever a stepping stone (the
    frontend saves a preset as a Draft, then adds the message from it). Soft-deleted only when it is a live DRAFT the same
    person created and nothing uses it: no campaign, no drip message, no journey step. Otherwise it stays, silently."""
    from apps.journeys.models import JourneyNode
    from apps.templates.models import TemplateMaster
    user_id = _user_id(user)
    if template is None or user_id is None or template.deleted_at is not None or template.status != TemplateMaster.Status.DRAFT or template.created_by_id != user_id:
        return False
    if (Campaign.objects.filter(template_id=template.pk, deleted_at__isnull=True).exists()
            or CampaignDripStep.objects.filter(template_id=template.pk).exists()
            or JourneyNode.objects.filter(journey_version__journey__tenant_id=template.tenant_id, deleted_at__isnull=True, config__template_id=str(template.pk)).exists()):
        return False
    return TemplateMaster.objects.filter(pk=template.pk, deleted_at__isnull=True).update(deleted_at=timezone.now(), updated_by_id=user_id) == 1


def _discard(campaign, template_id, owned: bool) -> None:
    """A step let go of its template: an own copy nothing else uses is soft-deleted; a shared template is left alone."""
    from apps.templates.models import TemplateMaster
    if not owned or template_id is None:
        return
    if CampaignDripStep.objects.filter(template_id=template_id).exists() or Campaign.objects.filter(template_id=template_id, deleted_at__isnull=True).exists():
        return
    TemplateMaster.objects.filter(pk=template_id, deleted_at__isnull=True).update(deleted_at=timezone.now())


# ---------------------------------------------------------------- creating and copying a drip
def seed(campaign, user=None) -> None:
    """A new drip: a row per drip_config step it was created with (an integration), or a Day-0 message, so the Sequence
    step never starts empty. Those rows use the campaign's template as it is, like a backfilled drip."""
    if campaign.campaign_type != Campaign.CampaignType.DRIP or CampaignDripStep.objects.filter(campaign=campaign).exists():
        return
    given = (campaign.drip_config or {}).get("steps") if not service.validate_drip(campaign.drip_config) else None
    steps = given or [{"day": 0}]
    CampaignDripStep.objects.bulk_create([CampaignDripStep(tenant_id=campaign.tenant_id, campaign=campaign, day=int(step["day"]), name=str(step.get("label") or "")[:200],
                                                           template_id=campaign.template_id, created_by_id=_user_id(user)) for step in steps])
    sync(campaign)


def follow_campaign(campaign, before_template_id, user=None) -> None:
    """The campaign itself was saved with a new drip_config or template (the setup before the Sequence step existed):
    the rows follow, then the mirror is rewritten. A message's own copy is never replaced from here."""
    if campaign.campaign_type != Campaign.CampaignType.DRIP:
        return
    if not CampaignDripStep.objects.filter(campaign=campaign).exists():
        seed(campaign, user)
        return
    dropped = []
    if campaign.template_id != before_template_id:
        CampaignDripStep.objects.filter(campaign=campaign, template_owned=False).filter(Q(template_id=before_template_id) | Q(template__isnull=True)).update(template_id=campaign.template_id)
    if not service.validate_drip(campaign.drip_config):
        wanted = {int(step["day"]): str(step.get("label") or "")[:200] for step in campaign.drip_config["steps"]}
        for step in steps_of(campaign):
            if step.day not in wanted:
                step.delete()
                dropped.append(step)
            elif wanted[step.day] and wanted[step.day] != step.name:
                CampaignDripStep.objects.filter(pk=step.pk).update(name=wanted[step.day])
        have = set(CampaignDripStep.objects.filter(campaign=campaign).values_list("day", flat=True))
        CampaignDripStep.objects.bulk_create([CampaignDripStep(tenant_id=campaign.tenant_id, campaign=campaign, day=day, name=name, template_id=campaign.template_id,
                                                               created_by_id=_user_id(user)) for day, name in wanted.items() if day not in have])
    sync(campaign)
    for step in dropped:
        _discard(campaign, step.template_id, step.template_owned)


def clone_steps(source, copy, user=None) -> None:
    """Every message again, each with a fresh copy of its template named for the new campaign."""
    from apps.templates import design
    if source.campaign_type != Campaign.CampaignType.DRIP:
        return
    steps = steps_of(source)
    rows = []
    for position, step in enumerate(steps, start=1):
        template = step.template if step.template_id and step.template.deleted_at is None else None
        rows.append(CampaignDripStep(tenant_id=copy.tenant_id, campaign=copy, day=step.day, name=step.name, send_time=step.send_time,
                                     template=design.clone_template(template, _user_id(user), name=_free_name(copy_name(copy, position, len(steps)))) if template else None, template_owned=template is not None,
                                     subject_line=step.subject_line, preheader=step.preheader, ab_config=step.ab_config, created_by_id=_user_id(user)))
    CampaignDripStep.objects.bulk_create(rows)
    if not rows:
        seed(copy, user)
    sync(copy)


# ---------------------------------------------------------------- the steps API
def _position(steps, step) -> int:
    return next(index for index, item in enumerate(steps, start=1) if item.pk == step.pk)


def _check_day(campaign, day, step=None) -> int:
    try:
        day = int(day)
    except (TypeError, ValueError):
        raise ValidationError({"day": ["Enter the day as a whole number (0 = the start date)."]}) from None
    if not 0 <= day <= 365:
        raise ValidationError({"day": ["A message's day has to be between 0 and 365."]})
    if CampaignDripStep.objects.filter(campaign=campaign, day=day).exclude(pk=getattr(step, "pk", None)).exists():
        raise ValidationError({"day": [SAME_DAY]})
    return day


def _check_ab(campaign, step, value):
    from apps.delivery.engine import abtest
    problem = abtest.validate(value)
    if problem:
        raise ValidationError({"ab_config": [problem]})
    if not (value or {}).get("enabled"):
        return value
    if campaign.channel != "EMAIL":
        raise ValidationError({"ab_config": ["A subject line test is for email: texts have no subject."]})
    steps = steps_of(campaign)
    other = next((item for item in steps if item.pk != getattr(step, "pk", None) and (item.ab_config or {}).get("enabled")), None)
    if other is not None:
        raise ValidationError({"ab_config": [f"Message {_position(steps, other)} is already being tested. One message per drip can have an A/B test."]})
    return value


def _clean_text(campaign, name: str, value):
    value = " ".join((value or "").split()) or None
    if value and campaign.channel in TEXT_CHANNELS:
        raise ValidationError({name: ["A text message has no subject line or preheader."]})
    if value and len(value) > 300:
        raise ValidationError({name: ["Use at most 300 characters."]})
    return value


def add_step(campaign, user, *, start_from: str, source_step=None, template=None, starter: str | None = None, day=None, name: str = "",
             consume_source_template: bool = False) -> CampaignDripStep:
    require_editable(campaign)
    steps = steps_of(campaign)
    if len(steps) >= MAX_STEPS:
        raise ValidationError({"day": [f"A drip has at most {MAX_STEPS} messages."]})
    day = _check_day(campaign, min(365, steps[-1].day + DEFAULT_GAP_DAYS) if day is None and steps else (0 if day is None else day))
    provisional = copy_name(campaign, len(steps) + 1, len(steps) + 1)
    values = {"name": " ".join((name or "").split())[:200]}
    if start_from == "copy":
        source = source_step or (steps[-1] if steps else None)
        if source is None or source.campaign_id != campaign.pk:
            raise ValidationError({"source_step": ["Choose a message of this drip to copy."]})
        if source.template_id and source.template.deleted_at is None:
            values.update(template=_copy_of(campaign, source.template, user, provisional), template_owned=True)
        values.update(subject_line=source.subject_line, preheader=source.preheader, send_time=source.send_time)
    elif start_from == "template":
        if template is not None:
            values.update(template=_copy_of(campaign, template, user, provisional), template_owned=True)
        elif starter:
            values.update(template=_from_starter(campaign, starter, user, provisional), template_owned=True)
        else:
            raise ValidationError({"template": ["Choose a template or a gallery template to start from."]})
    elif start_from == "blank":
        values.update(template=_blank(campaign, user, provisional), template_owned=True)
    else:
        raise ValidationError({"start_from": ["Start from a copy, a template or a blank message."]})
    step = CampaignDripStep.objects.create(tenant_id=campaign.tenant_id, campaign=campaign, day=day, created_by_id=_user_id(user), content_changed_at=timezone.now(), **values)
    if consume_source_template and start_from == "template" and template is not None:
        consume_source(template, user)
    steps = sync(campaign)
    _changed(campaign, user, f"Message {_position(steps, step)} added (Day {day}).")
    return step


EDITABLE_FIELDS = ("name", "day", "send_time", "subject_line", "preheader", "ab_config", "template")
WORDS = {"name": "name", "day": "day", "send_time": "send time", "subject_line": "subject line", "preheader": "preheader", "ab_config": "A/B test", "template": "template"}


def update_step(campaign, step, user, values: dict, row_version=None, consume_source_template: bool = False) -> CampaignDripStep:
    require_editable(campaign)
    if row_version is not None and str(row_version) != str(step.row_version):
        raise Conflict("Someone else changed this message after you opened it. Reload to see their changes.")
    changes, content = {}, False
    if "name" in values:
        changes["name"] = " ".join((values["name"] or "").split())[:200]
    if "day" in values:
        changes["day"] = _check_day(campaign, values["day"], step)
    if "send_time" in values:
        changes["send_time"] = values["send_time"]
    for name in ("subject_line", "preheader"):
        if name in values:
            changes[name] = _clean_text(campaign, name, values[name])
    if "ab_config" in values:
        changes["ab_config"] = _check_ab(campaign, step, values["ab_config"])
    old_template, old_owned = step.template_id, step.template_owned
    if "template" in values:
        chosen = values["template"]
        if chosen is None:
            raise ValidationError({"template": ["Choose a template. A message can't be left without one."]})
        if chosen.pk != step.template_id:
            changes["template"] = _copy_of(campaign, chosen, user, copy_name(campaign, 1, 1))
            changes["template_owned"] = True
    changed = [name for name, value in changes.items() if getattr(step, name) != value]
    if not changed:
        return step
    content = any(name in changed for name in ("template", "subject_line", "preheader", "ab_config"))
    for name in changed:
        setattr(step, name, changes[name])
    if content:
        step.content_changed_at = timezone.now()
    step.updated_by_id = _user_id(user)
    step.save(update_fields=[*changed, *(["content_changed_at"] if content else []), "updated_by"])
    steps = sync(campaign)
    if "template" in changed:
        _discard(campaign, old_template, old_owned)
        if consume_source_template:
            consume_source(values["template"], user)
    step = next(item for item in steps_of(campaign) if item.pk == step.pk)
    _changed(campaign, user, f"Message {_position(steps, step)} changed: " + ", ".join(WORDS[name] for name in changed if name in WORDS) + ".")
    return step


def remove_step(campaign, step, user) -> None:
    require_editable(campaign)
    steps = steps_of(campaign)
    if len(steps) <= 1:
        raise Conflict("A drip needs at least one message. Add another message before removing this one.")
    position = _position(steps, step)
    step.delete()
    sync(campaign)
    _discard(campaign, step.template_id, step.template_owned)
    _changed(campaign, user, f"Message {position} (Day {step.day}) removed.")


# ---------------------------------------------------------------- what the steps look like
def series_time(campaign) -> str | None:
    return (campaign.drip_config or {}).get("time") or None


def _clock(campaign, step, start: datetime | None) -> time | None:
    """The one rule for when a message goes out: its own send time, else the series time, else the start's own time of day."""
    if step.send_time is not None:
        return step.send_time.replace(second=0, microsecond=0)
    if series_time(campaign):
        hour, minute = (int(part) for part in str(series_time(campaign)).split(":")[:2])
        return time(hour, minute)
    if start is not None:
        return start.astimezone(service.zone_of(campaign)).time().replace(second=0, microsecond=0)
    return None


def effective_send_time(campaign, step) -> str | None:
    """HH:MM of the timetable; None while it depends on a start date that isn't set."""
    clock = _clock(campaign, step, campaign.scheduled_at)
    return clock.strftime("%H:%M") if clock else None


def scheduled_for(campaign, step, start: datetime | None = None) -> datetime | None:
    """When the message goes out: the start date (in the campaign's zone) + its day, at _clock. What create_runs plans, and
    what the API shows. `start` replaces campaign.scheduled_at (publishing a drip without a start date starts it now)."""
    start = start or campaign.scheduled_at
    if start is None:
        return None
    zone = service.zone_of(campaign)
    return datetime.combine(start.astimezone(zone).date() + timedelta(days=step.day), _clock(campaign, step, start), tzinfo=zone)


LATEST_CONTENT = "drip_steps__template__rendered_template_contents"


def latest_contents_prefetch():
    """For a list of campaigns: each message template's latest saved version only, and only what problems() reads."""
    from django.db.models import Prefetch
    from apps.templates.models import RenderedTemplateContent
    return Prefetch(LATEST_CONTENT, queryset=RenderedTemplateContent.objects.order_by("template_id", "-version_number").distinct("template_id")
                    .only("id", "template_id", "version_number", "subject_line", "sms_body"))


def _contents(steps) -> dict:
    from apps.templates.models import RenderedTemplateContent
    prefetched = [step.template for step in steps if step.template_id and "rendered_template_contents" in getattr(step.template, "_prefetched_objects_cache", {})]
    if prefetched and len(prefetched) == sum(1 for step in steps if step.template_id):
        return {template.pk: next(iter(template.rendered_template_contents.all()), None) for template in prefetched}
    ids = {step.template_id for step in steps if step.template_id}
    rows = RenderedTemplateContent.objects.filter(template_id__in=ids).order_by("template_id", "-version_number").distinct("template_id")
    return {row.template_id: row for row in rows}


def problems(campaign, step, contents: dict, days: list) -> list[str]:
    found = []
    template = step.template if step.template_id else None
    if template is None or template.deleted_at is not None:
        found.append("NEEDS_TEMPLATE")
    else:
        content = contents.get(step.template_id)
        if template.channel in TEXT_CHANNELS:
            if not (getattr(content, "sms_body", None) or "").strip():
                found.append("NEEDS_TEXT")
        elif not (step.subject_line or getattr(content, "subject_line", None) or "").strip():
            found.append("NEEDS_SUBJECT")
    if days.count(step.day) > 1:
        found.append("SAME_DAY")
    return found


def run_results(campaign, steps) -> dict:
    """{step_id: the step's production run with its results}, for the steps that have one. The same figures as the run and
    metrics endpoints (runs.stats_many, service.rate), one grouped query per measure for all the drip's runs."""
    from apps.delivery.engine import abtest, runs as engine_runs
    from .models import CampaignRun, CampaignRunVariant
    runs = list(CampaignRun.objects.filter(campaign=campaign, test_mode=False, drip_step_id__in=[step.pk for step in steps])
                .order_by("drip_step_id", "-run_number").distinct("drip_step_id"))
    if not runs:
        return {}
    kind = engine_runs.family(campaign)
    figures = engine_runs.stats_many(campaign.tenant_id, [run.pk for run in runs], kind)
    with service._conn().cursor() as cursor:
        cursor.execute("""SELECT campaign_run_id::text, count(*) FROM consent_record WHERE tenant_id = %s AND campaign_id = %s AND action = 'OPT_OUT'
                           AND campaign_run_id::text = ANY(%s) GROUP BY 1""", [str(campaign.tenant_id), str(campaign.pk), [str(run.pk) for run in runs]])
        opt_outs = dict(cursor.fetchall())
    tested = set(CampaignRunVariant.objects.filter(campaign_run__in=runs, deleted_at__isnull=True).values_list("campaign_run_id", flat=True))
    results = {}
    for run in runs:
        numbers, members = figures[str(run.pk)]["messages"], figures[str(run.pk)]["audience"]
        unsubscribed = max(int(opt_outs.get(str(run.pk), 0)), numbers["opted_out"])
        results[run.drip_step_id] = {
            "id": str(run.pk), "status": run.status, "scheduled_at": run.scheduled_at, "started_at": run.started_at, "completed_at": run.completed_at,
            "sent": numbers["sent"], "delivered": numbers["delivered"], "opened": numbers["opened"], "clicked": numbers["clicked"], "unsubscribed": unsubscribed,
            "open_rate": service.rate(numbers["opened"], numbers["delivered"]), "click_rate": service.rate(numbers["clicked"], numbers["delivered"]),
            "unsubscribe_rate": service.rate(unsubscribed, numbers["delivered"]), "not_sent": numbers["not_sent"],
            **({"replied": numbers["replied"], "opted_out": numbers["opted_out"]} if kind == "SMS" else {}),
            "skipped": {"total": sum(members["suppressed"].values()),
                        "by_reason": [{"reason": reason, "count": count} for reason, count in sorted(members["suppressed"].items(), key=lambda item: (-item[1], item[0]))]},
            "ab": {"variants": abtest.summary(run), "decide_at": run.ab_decide_at} if run.pk in tested else None}
    return results


EXCERPT_LENGTH = 140


def _excerpt(step, contents: dict) -> str | None:
    """A text message's first 140 characters as written (tags left as they are), from the latest content already loaded
    for problems(); None for email and for a message without text."""
    template = step.template if step.template_id else None
    if template is None or template.channel not in TEXT_CHANNELS:
        return None
    body = (getattr(contents.get(step.template_id), "sms_body", None) or "").strip()
    return body[:EXCERPT_LENGTH] or None


def payloads(campaign, steps=None, with_runs: bool = False, with_tests: bool = False) -> list[dict]:
    """The steps as the API shows them. `with_runs`: each with `run`, its production run and results (null until planned).
    `with_tests`: each with `test`, its test status (drip_publish.test_states)."""
    from . import drip_publish
    steps = steps if steps is not None else steps_of(campaign)
    contents, days = _contents(steps), [step.day for step in steps]
    runs = run_results(campaign, steps) if with_runs else {}
    tests = drip_publish.test_states(campaign, steps) if with_tests else {}
    return [{"id": str(step.pk), "position": position, "day": step.day, "name": step.name,
             "send_time": step.send_time.strftime("%H:%M") if step.send_time else None, "effective_send_time": effective_send_time(campaign, step),
             "scheduled_for": scheduled_for(campaign, step),
             "template": {"id": str(step.template.pk), "name": step.template.name, "channel": step.template.channel, "status": step.template.status}
             if step.template_id and step.template.deleted_at is None else None,
             "subject_line": step.subject_line, "preheader": step.preheader, "ab_config": step.ab_config, "text_excerpt": _excerpt(step, contents),
             "problems": problems(campaign, step, contents, days), "row_version": step.row_version,
             **({"run": runs.get(step.pk)} if with_runs else {}), **({"test": tests[step.pk]} if with_tests else {})}
            for position, step in enumerate(steps, start=1)]


def summary(campaign) -> dict | None:
    if campaign.campaign_type != Campaign.CampaignType.DRIP:
        return None
    steps = sorted(campaign.drip_steps.all(), key=lambda step: step.day)
    if not steps:
        return {"count": 0, "last_day": None, "first_send_at": None, "last_send_at": None, "ready": False}
    rows = payloads(campaign, steps)
    return {"count": len(steps), "last_day": steps[-1].day, "first_send_at": rows[0]["scheduled_for"], "last_send_at": rows[-1]["scheduled_for"],
            "ready": not any(row["problems"] for row in rows)}


# ---------------------------------------------------------------- template locks
def _use(template, statuses):
    step = (CampaignDripStep.objects.filter(template_id=template.pk, campaign__deleted_at__isnull=True, campaign__status__in=statuses)
            .select_related("campaign").order_by("-campaign__created_at", "day").first())
    if step is None:
        return None
    return step, _position(steps_of(step.campaign), step)


def guard_template(template, action: str) -> None:
    """action: "edit" (content or settings), "delete" or "archive". Templates no drip uses are never affected."""
    if action == "edit":
        use = _use(template, LIVE)
        if use:
            step, position = use
            raise Conflict(f"Used by a live drip ({step.campaign.name}, message {position}). It can't be changed until the drip finishes or is stopped.")
        return
    use = _use(template, RUNNING)
    if use:
        step, position = use
        verb = "archived" if action == "archive" else "deleted"
        raise Conflict(f"This template can't be {verb}. {step.campaign.name} uses it for message {position}, and the drip is still running.")


def used_in_drip(template) -> dict | None:
    step = (CampaignDripStep.objects.filter(template_id=template.pk, campaign__deleted_at__isnull=True).select_related("campaign")
            .order_by("-campaign__created_at", "day").first())
    if step is None:
        return None
    steps = steps_of(step.campaign)
    return {"campaign_id": str(step.campaign_id), "campaign_name": step.campaign.name, "position": _position(steps, step), "count": len(steps),
            "locked": step.campaign.status in LIVE}
